"""
Алгоритм битонной сортировки (Bitonic Sort)

Bitonic Sort - это параллельный алгоритм сортировки, основанный на построении 
и слиянии битонных последовательностей.

Битонная последовательность - это последовательность чисел, которая сначала 
монотонно возрастает, а затем монотонно убывает (или наоборот).

Время работы: O(n log² n)
Пространственная сложность: O(1) (сортировка in-place)
Особенность: Алгоритм особенно эффективен для параллельных вычислений

Алгоритм работает лучше всего, когда размер массива является степенью двойки.
Для массивов других размеров используется дополнение до ближайшей степени двойки.
"""


def compare_and_swap(arr, i, j, direction):
    """
    Сравнивает и при необходимости меняет местами два элемента массива.
    
    Эта функция является основным строительным блоком битонной сортировки.
    Она сравнивает элементы arr[i] и arr[j] и меняет их местами, если они
    находятся в неправильном порядке относительно заданного направления.
    
    Параметры:
    arr - массив для сортировки
    i - индекс первого элемента
    j - индекс второго элемента
    direction - направление сортировки:
                True (1) - по возрастанию (arr[i] должен быть меньше arr[j])
                False (0) - по убыванию (arr[i] должен быть больше arr[j])
    
    Пример:
    Если direction = True и arr[i] > arr[j], то элементы меняются местами.
    Если direction = False и arr[i] < arr[j], то элементы меняются местами.
    """
    # Сравниваем элементы в зависимости от направления
    # Если направление - по возрастанию (direction = True):
    #   меняем местами, если arr[i] > arr[j]
    # Если направление - по убыванию (direction = False):
    #   меняем местами, если arr[i] < arr[j]
    if (arr[i] > arr[j] and direction == True) or (arr[i] < arr[j] and direction == False):
        # Меняем элементы местами
        arr[i], arr[j] = arr[j], arr[i]


def bitonic_merge(arr, low, count, direction):
    """
    Сливает битонную последовательность в монотонную.
    
    Эта функция принимает битонную последовательность (последовательность,
    которая сначала возрастает, затем убывает, или наоборот) и преобразует
    её в полностью монотонную последовательность (только возрастающую или
    только убывающую).
    
    Алгоритм работает рекурсивно:
    1. Разделяет последовательность пополам
    2. Сравнивает соответствующие элементы из двух половин
    3. Меняет их местами при необходимости
    4. Рекурсивно применяет алгоритм к каждой половине
    
    Параметры:
    arr - массив для сортировки
    low - начальный индекс подпоследовательности
    count - количество элементов в подпоследовательности
    direction - направление сортировки (True - по возрастанию, False - по убыванию)
    
    Пример работы:
    Исходная битонная последовательность: [3, 4, 7, 8, 6, 5, 2, 1]
    После bitonic_merge с direction=True: [1, 2, 3, 4, 5, 6, 7, 8]
    """
    if count > 1:
        # Вычисляем среднюю точку для разделения последовательности
        k = count // 2
        
        # Сравниваем и меняем местами элементы из двух половин
        # Сравниваем arr[low + i] с arr[low + i + k] для всех i от 0 до k-1
        for i in range(low, low + k):
            compare_and_swap(arr, i, i + k, direction)
        
        # Рекурсивно применяем слияние к каждой половине
        # Левая половина: от low до low + k
        bitonic_merge(arr, low, k, direction)
        # Правая половина: от low + k до low + count
        bitonic_merge(arr, low + k, k, direction)


def bitonic_sort_recursive(arr, low, count, direction):
    """
    Рекурсивно строит битонную последовательность и затем сливает её.
    
    Это основная рекурсивная функция битонной сортировки. Она работает в два этапа:
    
    1. Построение битонной последовательности:
       - Разделяет массив пополам
       - Рекурсивно строит битонную последовательность в каждой половине
       - Одна половина сортируется по возрастанию, другая - по убыванию
       - Это создает битонную последовательность
    
    2. Слияние битонной последовательности:
       - Использует bitonic_merge для преобразования битонной последовательности
         в полностью отсортированную последовательность
    
    Параметры:
    arr - массив для сортировки
    low - начальный индекс подпоследовательности
    count - количество элементов в подпоследовательности
    direction - направление сортировки (True - по возрастанию, False - по убыванию)
    
    Рекурсивная структура:
    - Базовый случай: count <= 1 (последовательность уже отсортирована)
    - Рекурсивный случай:
      1. Разделить последовательность пополам
      2. Отсортировать левую половину в направлении direction
      3. Отсортировать правую половину в противоположном направлении
      4. Слить две половины в одну отсортированную последовательность
    """
    if count > 1:
        # Вычисляем среднюю точку для разделения
        k = count // 2
        
        # Этап 1: Построение битонной последовательности
        # Сортируем левую половину в заданном направлении
        bitonic_sort_recursive(arr, low, k, direction)
        # Сортируем правую половину в противоположном направлении
        # Это создает битонную последовательность: одна половина возрастает,
        # другая убывает (или наоборот)
        bitonic_sort_recursive(arr, low + k, k, not direction)
        
        # Этап 2: Слияние битонной последовательности в монотонную
        # После этого этапа вся последовательность будет отсортирована
        # в заданном направлении
        bitonic_merge(arr, low, count, direction)


def bitonic_sort(arr):
    """
    Основная функция битонной сортировки.
    
    Битонная сортировка - это параллельный алгоритм сортировки, который
    особенно эффективен для параллельных вычислений. Алгоритм работает
    лучше всего, когда размер массива является степенью двойки.
    
    Алгоритм:
    1. Если размер массива не является степенью двойки, дополняем массив
       максимальным значением до ближайшей степени двойки
    2. Вызываем рекурсивную функцию bitonic_sort_recursive для сортировки
       по возрастанию
    3. Удаляем добавленные элементы перед возвратом результата
    
    Параметры:
    arr - массив для сортировки (будет изменен in-place)
    
    Возвращает:
    Отсортированный массив по возрастанию
    
    Временная сложность: O(n log² n)
    Пространственная сложность: O(1) (in-place, не считая рекурсивного стека)
    
    Пример:
    [3, 7, 4, 8, 6, 2, 1, 5] -> [1, 2, 3, 4, 5, 6, 7, 8]
    """
    n = len(arr)
    
    # Обработка пустого массива
    if n == 0:
        return arr
    
    # Обработка массива с одним элементом
    if n == 1:
        return arr
    
    # Находим ближайшую степень двойки, большую или равную n
    # Это необходимо, так как битонная сортировка работает лучше всего
    # с массивами размером, равным степени двойки
    next_power_of_2 = 1
    while next_power_of_2 < n:
        next_power_of_2 *= 2
    
    # Если размер массива не является степенью двойки, дополняем массив
    # Используем максимальное значение из массива для дополнения
    # Это гарантирует, что добавленные элементы окажутся в конце
    # после сортировки
    original_n = n
    if n != next_power_of_2:
        max_val = max(arr) if arr else 0
        # Дополняем массив до степени двойки
        arr.extend([max_val] * (next_power_of_2 - n))
        n = next_power_of_2
    
    # Вызываем рекурсивную функцию сортировки
    # direction = True означает сортировку по возрастанию
    bitonic_sort_recursive(arr, 0, n, True)
    
    # Удаляем добавленные элементы, если массив был дополнен
    if original_n != n:
        arr[:] = arr[:original_n]
    
    return arr


# Пример использования
